#!/usr/bin/env bun
/**
 * Stamps the copyright header defined in docs/licensing.md onto Core source
 * files.
 *
 * Per-file headers are optional in this repository — the root LICENSE governs
 * regardless, and stamping ~1,000 files adds permanent diff noise. This script
 * exists for the cases where headers are actually wanted: sharing a subset of
 * the code outside the repository, or a customer's counsel asking for them.
 *
 * It lives in tools/ rather than scripts/ because scripts/ is gitignored for
 * local-only helpers, and this one is referenced from docs/licensing.md.
 *
 * It is deliberately not wired into CI, lint-staged, or any package script.
 *
 *   bun run tools/stamp-copyright-headers.mjs --check   # report, change nothing
 *   bun run tools/stamp-copyright-headers.mjs --write   # apply
 *   bun run tools/stamp-copyright-headers.mjs --write --path src/lib
 */

import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";

const ROOT = resolve(import.meta.dirname, "..");
const YEAR = new Date().getFullYear();
const HOLDER = "Rickie Cruz McDougal";

const HEADER = `/**
 * Copyright (c) ${YEAR} ${HOLDER}. All rights reserved.
 * Licensed under the terms in LICENSE at the repository root.
 */
`;

// Matched loosely so a header stamped in an earlier year is left alone rather
// than duplicated.
const EXISTING = /Copyright \(c\) \d{4}/;

const EXTENSIONS = [".ts", ".tsx", ".mjs", ".js", ".jsx"];
const SKIP_DIRS = new Set([
  "node_modules",
  ".next",
  ".git",
  "playwright-report",
  "test-results",
  "generated",
  ".playwright-mcp",
]);
// next-env.d.ts is generated by Next.js and rewritten on every typegen run.
const SKIP_FILES = new Set(["next-env.d.ts"]);

const args = process.argv.slice(2);
const write = args.includes("--write");
const check = args.includes("--check") || !write;
const pathArgIndex = args.indexOf("--path");
const target =
  pathArgIndex !== -1 && args[pathArgIndex + 1]
    ? resolve(ROOT, args[pathArgIndex + 1])
    : ROOT;

function* walk(dir) {
  for (const entry of readdirSync(dir)) {
    if (SKIP_DIRS.has(entry) || SKIP_FILES.has(entry)) continue;
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) {
      yield* walk(full);
    } else if (EXTENSIONS.some((ext) => entry.endsWith(ext))) {
      yield full;
    }
  }
}

const missing = [];
for (const file of walk(target)) {
  const source = readFileSync(file, "utf8");
  if (EXISTING.test(source.slice(0, 400))) continue;
  missing.push(file);
  if (write) {
    // A "use client" / "use server" directive must stay the first statement, so
    // the header goes after it rather than above it.
    const directive = source.match(/^(["'])use (client|server)\1;?\r?\n/);
    const updated = directive
      ? source.slice(0, directive[0].length) +
        HEADER +
        source.slice(directive[0].length)
      : HEADER + source;
    writeFileSync(file, updated);
  }
}

const label = write ? "stamped" : "missing a header";
console.log(`${missing.length} file(s) ${label}.`);
if (check && !write && missing.length > 0) {
  for (const file of missing.slice(0, 20)) {
    console.log(`  ${relative(ROOT, file)}`);
  }
  if (missing.length > 20) console.log(`  ...and ${missing.length - 20} more`);
  console.log("\nRun with --write to apply. Format afterwards: bun run format");
}
